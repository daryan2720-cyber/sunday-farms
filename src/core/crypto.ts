/**
 * Small, dependency-free SHA-256, HMAC-SHA256 and PBKDF2 so the in-app demo server and the
 * QR label check work the same on iOS, Android and in tests. Random bytes come from the
 * platform's secure generator (expo-crypto in the app, node:crypto in tests).
 */

type RandomSource = (n: number) => Uint8Array;

let randomSource: RandomSource = (n) => {
  const out = new Uint8Array(n);
  const c = (globalThis as { crypto?: { getRandomValues?: (a: Uint8Array) => Uint8Array } }).crypto;
  if (!c?.getRandomValues) throw new Error('No secure random source set');
  c.getRandomValues(out);
  return out;
};

export function setRandomSource(fn: RandomSource): void {
  randomSource = fn;
}

export function randomBytes(n: number): Uint8Array {
  return randomSource(n);
}

export function utf8(s: string): Uint8Array {
  return new TextEncoder().encode(s);
}

export function toHex(b: Uint8Array): string {
  let s = '';
  for (let i = 0; i < b.length; i++) s += b[i].toString(16).padStart(2, '0');
  return s;
}

export function fromHex(h: string): Uint8Array {
  const out = new Uint8Array(h.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(h.slice(i * 2, i * 2 + 2), 16);
  return out;
}

const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';

/** URL-safe base64 without padding (for tokens). */
export function base64Url(b: Uint8Array): string {
  let out = '';
  for (let i = 0; i < b.length; i += 3) {
    const n = (b[i] << 16) | ((b[i + 1] ?? 0) << 8) | (b[i + 2] ?? 0);
    out += B64[(n >> 18) & 63] + B64[(n >> 12) & 63];
    if (i + 1 < b.length) out += B64[(n >> 6) & 63];
    if (i + 2 < b.length) out += B64[n & 63];
  }
  return out;
}

export function randomToken(bytes = 32): string {
  return base64Url(randomBytes(bytes));
}

/** A uniformly random 6-digit code (100000-999999). */
export function randomCode(): string {
  const b = randomBytes(4);
  const n = ((b[0] << 24) | (b[1] << 16) | (b[2] << 8) | b[3]) >>> 0;
  return String(100000 + (n % 900000));
}

